namespace D47.Core.Stories;

/// <summary>The style rule every prompt that writes text the Commander reads or hears carries.</summary>
public static class PlainWords
{
    public const string Rule =
        "Write plainly. Say what happens in the game's own terms: name the station, the system and the rank "
        + "(Powerplay rank 6, Imperial Navy rank Outsider), and call cargo cargo. Do not use a metaphor or an image "
        + "where a direct statement would do: no book, ledger, file, column, door or address standing for a rank, a goal, "
        + "a station or a record. Do not give a game system a feature it does not have. An invented thing in the story, "
        + "such as a note, a letter or a log, is a real object in the fiction and is described as one. A character's manner "
        + "may change the words chosen, never what is said. Every sentence makes sense to a Commander who hears it alone. "
        + "A place is called by its name, never by a figurative name. Do not end a line on an aphorism or a moral.";
}
