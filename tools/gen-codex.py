#!/usr/bin/env python3
"""Regenerate d47's table of codex entries known per galactic region.

Not part of the build. Its output is committed as `src/D47.Core/Knowledge/Codex.tsv` and
shipped as an embedded resource; the app never runs this and never reaches Canonn.

    python tools/gen-codex.py

Source: Canonn's codex extracts, written daily by Dumpr (github.com/canonn-science/Dumpr, MIT),
whose README allows third-party tools to use them. The reference lists one object per EntryID
with the URL of that entry's CSV. Each CSV has no header and one row per reported entry:
system name, x, y, z, EntryID, system address, coordRegion, boxelRegion. boxelRegion is the
region the game wrote in that CodexEntry.

Entries whose hud_category is Thargoid or None are left out.
"""

import csv
import io
import json
import sys
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import date
from pathlib import Path

REFERENCE_URL = "https://us-central1-canonn-api-236217.cloudfunctions.net/query/codex/ref"

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "D47.Core" / "Knowledge" / "Codex.tsv"

EXCLUDED_HUD_CATEGORIES = {"Thargoid", "None"}

CATEGORIES = {
    "$Codex_Category_Biology;": "Biological and Geological",
    "$Codex_Category_StellarBodies;": "Astronomical Bodies",
    "$Codex_Category_Civilisations;": "Xenological",
}

SUB_CATEGORIES = {
    "$Codex_SubCategory_Organic_Structures;": "Organic structures",
    "$Codex_SubCategory_Geology_and_Anomalies;": "Geology and anomalies",
    "$Codex_SubCategory_Gas_Giants;": "Gas giant planets",
    "$Codex_SubCategory_Guardian;": "Guardian objects",
}

COLUMNS = 8

# Cloud Storage answers 403 for an object that was never written; it is an entry nobody has reported.
MISSING_OBJECT = {403, 404}
WORKERS = 8


def fetch(url: str) -> bytes:
    last = None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(url, timeout=120) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            if error.code in MISSING_OBJECT:
                raise
            last = error
            time.sleep(2 * (attempt + 1))
        except OSError as error:
            last = error
            time.sleep(2 * (attempt + 1))
    raise last


def regions_of(entry_id: str, url: str) -> dict[int, int]:
    try:
        text = fetch(url).decode("utf-8")
    except urllib.error.HTTPError as error:
        if error.code in MISSING_OBJECT:
            print(f"entry {entry_id}: no dump object ({error.code}); written with no regions")
            return {}
        raise SystemExit(f"entry {entry_id}: dump {url} failed to download: {error}")
    except OSError as error:
        raise SystemExit(f"entry {entry_id}: dump {url} failed to download: {error}")

    addresses: dict[int, set[str]] = {}

    for number, row in enumerate(csv.reader(io.StringIO(text)), start=1):
        if len(row) != COLUMNS:
            raise SystemExit(f"entry {entry_id}: dump row {number} has {len(row)} columns, expected {COLUMNS}")

        try:
            region = int(row[7])
        except ValueError:
            raise SystemExit(f"entry {entry_id}: dump row {number} has boxelRegion {row[7]!r}")

        addresses.setdefault(region, set()).add(row[5])

    return {region: len(found) for region, found in addresses.items()}


def main() -> int:
    started = time.time()
    reference = json.loads(fetch(REFERENCE_URL).decode("utf-8"))

    chosen = []

    for key, entry in reference.items():
        if entry["hud_category"] in EXCLUDED_HUD_CATEGORIES:
            continue

        for field, mapping in (("category", CATEGORIES), ("sub_category", SUB_CATEGORIES)):
            if entry[field] not in mapping:
                raise SystemExit(f"entry {key}: no English mapping for {field} {entry[field]!r}")

        chosen.append((int(entry["entryid"]), entry))

    chosen.sort(key=lambda pair: pair[0])

    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        counts = list(pool.map(lambda pair: regions_of(str(pair[0]), pair[1]["dump"]), chosen))

    lines = [
        "# Generated by tools/gen-codex.py. Do not edit by hand — rerun the tool.",
        f"# Source: Canonn codex extracts written by Dumpr (github.com/canonn-science/Dumpr, MIT), {date.today().isoformat()}.",
        "# Columns: EntryID, English name, category, subcategory, regions as id:systems pairs.",
        "# A region is listed when the game recorded the entry there at least once (boxelRegion);",
        "# systems is the number of distinct system addresses reported with it. Thargoid entries are left out.",
        "# Names and categories are Frontier's own game data; see NOTICE.",
        f"# Entries: {len(chosen)}.",
    ]

    for (entry_id, entry), found in zip(chosen, counts):
        regions = ",".join(f"{region}:{systems}" for region, systems in sorted(found.items()))
        name = entry["english_name"]
        lines.append(
            f"{entry_id}\t{name}\t{CATEGORIES[entry['category']]}\t{SUB_CATEGORIES[entry['sub_category']]}\t{regions}"
        )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    print(f"Wrote {len(chosen)} entries to {OUTPUT} in {time.time() - started:.0f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
