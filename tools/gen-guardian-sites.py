#!/usr/bin/env python3
"""Regenerate d47's Guardian sites table.

Not part of the build. Its output is committed as `src/D47.Core/Knowledge/GuardianSites.tsv` and
shipped as an embedded resource; the app never runs this and never reaches the network for it.
Run it when the galaxy search host lists new Guardian sites:

    python tools/gen-guardian-sites.py

Pages spansh.co.uk's body search by every Guardian landmark type and subtype, joins the rows by
body, and writes one row per body that holds a ruin or a structure. A body is a structure when it
has a "Guardian Structure" landmark, a "Guardian Data Terminal" or a "Guardian Pylon"; any other
body with a "Guardian Ruin" landmark, a "Guardian Codex", a "Guardian Relic Tower" or a "Guardian
Sentinel" is a ruin. A body with a "Guardian Beacon" and none of those is left out.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

from body_conditions import PAGE_SIZE, PAUSE, search

AGENT = "d47-gen-guardian-sites"

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "D47.Core" / "Knowledge" / "GuardianSites.tsv"

STRUCTURE_TYPES = {"Guardian Structure"}
STRUCTURE_SUBTYPES = {"Guardian Data Terminal", "Guardian Pylon"}
RUIN_TYPES = {"Guardian Ruin"}
RUIN_SUBTYPES = {"Guardian Codex", "Guardian Relic Tower", "Guardian Sentinel"}
LAYOUTS = ["Bear", "Bowl", "Crossroads", "Fistbump", "Hammerbot", "Lacrosse", "Robolobster", "Squid", "Turtle"]

FILTERS = [
    *(("landmark_type", value) for value in sorted(STRUCTURE_TYPES | RUIN_TYPES)),
    *(("landmark_subtype", value) for value in sorted(STRUCTURE_SUBTYPES | RUIN_SUBTYPES)),
    *(("landmark_subtype", value) for value in LAYOUTS),
]


def every_page(field: str, value: str) -> list[dict[str, object]]:
    bodies: list[dict[str, object]] = []
    page = 0

    while True:
        found = search(value, page, AGENT, field)
        bodies += found
        time.sleep(PAUSE)

        if len(found) < PAGE_SIZE:
            return bodies

        page += 1


def kind(landmarks: list[dict[str, object]]) -> str | None:
    types = {str(landmark.get("type", "")) for landmark in landmarks}
    subtypes = {str(landmark.get("subtype", "")) for landmark in landmarks}

    if types & STRUCTURE_TYPES or subtypes & STRUCTURE_SUBTYPES:
        return "structure"

    if types & RUIN_TYPES or subtypes & RUIN_SUBTYPES:
        return "ruin"

    return None


def number(value: object) -> str:
    return f"{float(str(value)):.5f}".rstrip("0").rstrip(".")


def main() -> int:
    bodies: dict[int, dict[str, object]] = {}

    for index, (field, value) in enumerate(FILTERS, start=1):
        found = every_page(field, value)

        for body in found:
            bodies[int(str(body["id64"]))] = body

        print(f"  [{index}/{len(FILTERS)}] {field} {value} — {len(found)} bodies", file=sys.stderr)

    rows: list[list[str]] = []

    for body in bodies.values():
        landmarks = body.get("landmarks") or []
        assert isinstance(landmarks, list)
        site = kind(landmarks)

        if site is None:
            continue

        subtypes = {str(landmark.get("subtype", "")) for landmark in landmarks}
        layouts = [layout for layout in LAYOUTS if layout in subtypes] if site == "structure" else []

        rows.append([
            str(body["system_name"]),
            str(body["system_id64"]),
            number(body["system_x"]),
            number(body["system_y"]),
            number(body["system_z"]),
            str(body["name"]),
            site,
            ";".join(layouts),
        ])

    if not rows:
        raise SystemExit("spansh lists no Guardian ruin or structure")

    rows.sort(key=lambda cells: (cells[0], cells[5]))
    systems = len({cells[1] for cells in rows})

    header = [
        "# Generated by tools/gen-guardian-sites.py. Do not edit by hand — rerun the tool.",
        f"# Source: spansh.co.uk api/bodies/search, {time.strftime('%Y-%m-%d', time.gmtime())}. Every body with a Guardian",
        "# ruin or structure landmark, joined by body. A body with a Guardian Structure, Data Terminal or",
        "# Pylon is a structure; any other with a Guardian Ruin, Codex, Relic Tower or Sentinel is a ruin.",
        "# layouts lists the structure layouts the service names. Game data is Frontier's, used under",
        "# their media usage rules; see NOTICE.",
        "system\taddress\tx\ty\tz\tbody\tkind\tlayouts",
    ]

    OUTPUT.write_text(
        "\n".join(header + ["\t".join(cells) for cells in rows]) + "\n",
        encoding="utf-8",
        newline="\n")

    print(f"\nWrote {len(rows)} bodies in {systems} systems to {OUTPUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
