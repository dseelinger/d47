#!/usr/bin/env python3
"""Regenerate d47's table of mission names.

Not part of the build. Its output is committed as `src/D47.Core/Knowledge/Missions.tsv` and
shipped as an embedded resource; the app never runs this. Re-run it when Frontier adds
missions or when more journals are available:

    python tools/gen-missions.py <journal folder> [<journal folder> ...]

Names come from two places where a commander accepted the mission: the keys of the array in
EDSM-NET/Alias `Station/Mission/Type.php` at a pinned revision (names only, never its display
strings), and `Name` of every `MissionAccepted` in `Journal.*.log` under the folders given.

`curated_missions.py` maps each name's family to a group and spoken words, and each name-ending
word to a circumstance. The script exits, naming the name and the word, on anything unmapped.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

import curated_missions as curated

REPOSITORY = "https://github.com/EDSM-NET/Alias"
REVISION = "52023a71b8bd8d77f06911d14e4a62e0fd7fa01a"
SOURCE = f"https://raw.githubusercontent.com/EDSM-NET/Alias/{REVISION}/Station/Mission/Type.php"

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "D47.Core" / "Knowledge" / "Missions.tsv"

KINDS = ["state", "government", "economy", "rank", "engineer"]

# A mission key in the array: 'mission_courier_boom' => 3. The display strings sit on the
# other side of the arrow and are never read.
KEY = re.compile(r"^\s*'([a-z0-9_]+)'\s*=>\s*\d+\s*,", re.MULTILINE)


def edsm_names() -> set[str]:
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "d47-gen-missions"})
    with urllib.request.urlopen(request, timeout=60) as response:
        php = response.read().decode("utf-8")

    names = set(KEY.findall(php))
    if len(names) < 500:
        raise SystemExit(f"Only {len(names)} names in the Type.php array; expected 532 or more.")
    return {name.lower() for name in names}


def journal_names(folders: list[Path]) -> set[str]:
    names: set[str] = set()
    for folder in folders:
        for path in sorted(folder.glob("Journal.*.log")):
            with path.open(encoding="utf-8", errors="replace") as lines:
                for line in lines:
                    if '"MissionAccepted"' not in line:
                        continue
                    try:
                        name = json.loads(line).get("Name")
                    except json.JSONDecodeError:
                        continue
                    if isinstance(name, str) and name:
                        names.add(name.lower())
    return names


def family_of(name: str) -> str | None:
    matches = [f for f in curated.FAMILIES if name.startswith(f.lower())]
    return max(matches, key=len) if matches else None


def row_for(name: str, problems: list[str]) -> list[str] | None:
    if any(name.startswith(prefix.lower()) for prefix in curated.NOT_ON_BOARD):
        return None

    family = family_of(name)
    if family is None:
        problems.append(f"{name}: no family")
        return None

    group, words, station_state = curated.FAMILIES[family]
    found: dict[str, str] = {}
    variants: list[str] = []

    for word in [w for w in name[len(family):].split("_") if w]:
        if curated.NUMBER.match(word):
            variants.append(word)
            continue
        mapped = curated.WORDS.get(word)
        if mapped is None:
            problems.append(f"{name}: unmapped word '{word}'")
            continue
        kind, value = mapped
        if kind == "variant":
            variants.append(value)
        elif kind in found:
            problems.append(f"{name}: two {kind} words, '{found[kind]}' and '{word}'")
        else:
            found[kind] = value

    return [name, family, group, words, found.get("state", ""), found.get("government", ""),
            found.get("economy", ""), found.get("rank", ""), found.get("engineer", ""),
            station_state, ",".join(variants)]


def main() -> None:
    folders = [Path(argument) for argument in sys.argv[1:]]
    if not folders or not all(folder.is_dir() for folder in folders):
        raise SystemExit("Usage: gen-missions.py <journal folder> [<journal folder> ...]")

    names = edsm_names() | journal_names(folders)
    problems: list[str] = []
    rows = [row for name in sorted(names) if (row := row_for(name, problems)) is not None]

    if problems:
        raise SystemExit("\n".join(problems))

    header = [
        "# Generated by tools/gen-missions.py. Do not edit by hand — rerun the tool.",
        f"# Sources: {REPOSITORY} at {REVISION}, Station/Mission/Type.php, key names only;",
        "# MissionAccepted.Name in the journal folders given on the command line.",
        "# Mission names are Frontier game data; see NOTICE.",
        "# name\tfamily\tgroup\twords\tstate\tgovernment\teconomy\trank\tengineer\tstation_state\tvariants",
    ]
    text = "\n".join(header + ["\t".join(row) for row in rows]) + "\n"
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(rows)} names to {OUTPUT}")


if __name__ == "__main__":
    main()
