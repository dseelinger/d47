#!/usr/bin/env python3
"""Regenerate d47's geology table.

Not part of the build. Its output is committed as `src/D47.Core/Knowledge/Geology.tsv` and
shipped as an embedded resource; the app never runs this and never reaches the network for it.
Run it when Frontier adds a surface feature:

    python tools/gen-geology.py

`GeologyCatalogue.Likely` predicts which geological features a scanned body could hold from
its planet class, atmosphere and volcanism. This generator learns the allowed values from
spansh.co.uk's surveyed bodies, sampled as `gen-exobiology.py` samples species. The feature
names and EntryIDs come from the committed `Codex.tsv`; the run fails when a name has no row
there.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

from body_conditions import (
    CATEGORICAL_THRESHOLD,
    PAGE_SIZE,
    PAUSE,
    categorical,
    normalise_atmosphere,
    normalise_planet_type,
    normalise_volcanism,
    search,
)

AGENT = "d47-gen-geology"

KNOWLEDGE = Path(__file__).resolve().parent.parent / "src" / "D47.Core" / "Knowledge"
CODEX = KNOWLEDGE / "Codex.tsv"
OUTPUT = KNOWLEDGE / "Geology.tsv"

FEATURES = [
    *(f"{kind} Fumarole" for kind in (
        "Sulphur Dioxide", "Water", "Carbon Dioxide", "Silicate Vapour", "Sulphur Dioxide Ice",
        "Water Ice", "Carbon Dioxide Ice", "Ammonia Ice", "Methane Ice", "Nitrogen Ice",
        "Silicate Vapour Ice")),
    *(f"{kind} Geyser" for kind in (
        "Water", "Water Ice", "Carbon Dioxide Ice", "Ammonia Ice", "Methane Ice", "Nitrogen Ice")),
    "Silicate Magma Lava Spout",
    "Iron Magma Lava Spout",
    *(f"{kind} Gas Vent" for kind in ("Sulphur Dioxide", "Water", "Carbon Dioxide", "Silicate Vapour")),
]


def entry_ids() -> dict[str, str]:
    ids: dict[str, str] = {}

    for line in CODEX.read_text(encoding="utf-8").splitlines():
        cells = line.split("\t")

        if line.startswith("#") or len(cells) < 4 or cells[3] != "Geology and anomalies":
            continue

        ids[cells[1]] = cells[0]

    missing = [name for name in FEATURES if name not in ids]

    if missing:
        raise SystemExit(f"no Codex.tsv row for: {', '.join(missing)}")

    return ids


def sample(name: str) -> list[dict[str, object]]:
    bodies = search(name, 0, AGENT)

    if len(bodies) == PAGE_SIZE:
        time.sleep(PAUSE)
        bodies += search(name, 1, AGENT)

    return bodies


def row(entry_id: str, name: str, bodies: list[dict[str, object]]) -> list[str]:
    def column(values: list[str]) -> str:
        return ";".join(categorical(values, CATEGORICAL_THRESHOLD)) if values else ""

    return [
        entry_id,
        name,
        column([normalise_planet_type(str(b.get("subtype", ""))) for b in bodies]),
        column([normalise_atmosphere(b.get("atmosphere")) for b in bodies]),
        column([normalise_volcanism(b.get("volcanism_type")) for b in bodies]),
    ]


def main() -> int:
    ids = entry_ids()
    rows: list[list[str]] = []

    for index, name in enumerate(FEATURES, start=1):
        bodies = sample(name)
        time.sleep(PAUSE)

        if not bodies:
            raise SystemExit(f"spansh has no surveyed body with {name}")

        rows.append(row(ids[name], name, bodies))
        print(f"  [{index}/{len(FEATURES)}] {name} — {len(bodies)} bodies", file=sys.stderr)

    rows.sort(key=lambda cells: int(cells[0]))

    header = [
        "# Generated by tools/gen-geology.py. Do not edit by hand — rerun the tool.",
        f"# Source: spansh.co.uk api/bodies/search, {time.strftime('%Y-%m-%d', time.gmtime())}. Up to 500 surveyed bodies",
        "# sampled per feature by landmark_subtype; a categorical value is kept when it is on at least 2% of",
        "# that feature's sampled bodies. Game data is Frontier's, used under their media usage rules;",
        "# see NOTICE. Planet type, atmosphere and volcanism are normalised by body_conditions.py in tools/,",
        "# mirrored in BodyConditionFold, which applies the same fold to a live journal Scan.",
        "# EntryID is the feature's EntryID in Codex.tsv.",
        "entry_id\tname\tplanet_types\tatmospheres\tvolcanism",
    ]

    OUTPUT.write_text(
        "\n".join(header + ["\t".join(cells) for cells in rows]) + "\n",
        encoding="utf-8",
        newline="\n")

    print(f"\nWrote {len(rows)} features to {OUTPUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
