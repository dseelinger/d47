#!/usr/bin/env python3
"""Regenerate d47's table of starter systems.

Not part of the build. Its output is committed as `src/D47.Core/Knowledge/StarterSystems.tsv`
and shipped as an embedded resource. Run it by hand on journal folders when a new starter zone
may exist:

    python tools/gen-starters.py <journal folder> [<journal folder> ...]

A starter system is the system of the first `Location` after a `NewCommander` event, when that
system is permit-locked (listed in `PermitSystems.tsv`). The tool merges the systems it finds
with those already in the table; it never removes one.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Iterable

ROOT = Path(__file__).resolve().parent.parent
PERMITS = ROOT / "src" / "D47.Core" / "Knowledge" / "PermitSystems.tsv"
OUTPUT = ROOT / "src" / "D47.Core" / "Knowledge" / "StarterSystems.tsv"

EXPECTED = ["HIP 97950"]


def read_table(path: Path) -> set[str]:
    if not path.is_file():
        return set()

    return {
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    }


def starters(lines: Iterable[str], locked: set[str]) -> set[str]:
    """Locked systems of the first Location after each NewCommander in one journal's lines."""
    folded = {name.casefold() for name in locked}
    found: set[str] = set()
    waiting = False

    for line in lines:
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue

        if not isinstance(entry, dict):
            continue

        event = entry.get("event")

        if event == "NewCommander":
            waiting = True
        elif event == "Location" and waiting:
            waiting = False
            system = str(entry.get("StarSystem", "")).strip()

            if system and system.casefold() in folded:
                found.add(system)

    return found


def main(argv: list[str]) -> int:
    if not argv:
        print("usage: gen-starters.py <journal folder> [<journal folder> ...]", file=sys.stderr)
        return 2

    locked = read_table(PERMITS)
    assert locked, f"{PERMITS} is empty or missing"

    found = read_table(OUTPUT)

    for folder in argv:
        for journal in sorted(Path(folder).rglob("Journal.*.log")):
            with journal.open(encoding="utf-8", errors="replace") as handle:
                found |= starters(handle, locked)

    missing = [name for name in EXPECTED if name not in found]
    assert not missing, f"starter systems the run never saw: {', '.join(missing)}"

    header = [
        "# Generated by tools/gen-starters.py. Do not edit by hand — rerun the tool.",
        "# The permit-locked system of the first Location after a NewCommander event.",
        "# System names only, which are Frontier's game data; see NOTICE.",
    ]

    OUTPUT.write_text("\n".join(header + sorted(found)) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(found)} rows to {OUTPUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
