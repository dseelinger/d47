#!/usr/bin/env python3
"""Regenerate d47's material trader table.

Not part of the build. Its output is committed as
`src/D47.Core/Knowledge/MaterialTraders.tsv` and shipped as an embedded resource; the app never
runs this. The list is frozen at the pinned commit, so the output does not change unless the
pin does:

    python tools/gen-material-traders.py

Source: `traders.jsonl` in jixxed/ed-odyssey-materials-helper (MIT), built from the game's
MaterialTrade events. One JSON object per line; `station.id` is the MarketID the journal writes
and `station.type` is Raw, Manufactured or Encoded.

Game data is Frontier's, used under their media usage rules. See `NOTICE`.
"""

import json
import urllib.request
from pathlib import Path

OMH_COMMIT = "f9083c4c91d5937b2d17ab37085593034eed045d"

SOURCE = (
    f"https://raw.githubusercontent.com/jixxed/ed-odyssey-materials-helper/{OMH_COMMIT}"
    "/application/src/main/resources/materialtrader/traders.jsonl"
)

TYPES = ("Raw", "Manufactured", "Encoded")

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "D47.Core" / "Knowledge" / "MaterialTraders.tsv"

COLUMNS = ["MarketID", "Type", "System", "Station"]


def fetch() -> str:
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "d47-gen-material-traders"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def main() -> None:
    rows: dict[int, tuple[str, str, str]] = {}

    for line in fetch().splitlines():
        if not line.strip():
            continue
        entry = json.loads(line)
        station = entry["station"]
        market_id = int(station["id"])
        kind = station["type"]
        if kind not in TYPES:
            raise SystemExit(f"station {market_id} has type {kind!r}, expected one of {TYPES}")
        if market_id in rows:
            raise SystemExit(f"MarketID {market_id} appears twice")
        rows[market_id] = (kind, entry["name"], station["name"])

    if not rows:
        raise SystemExit("the source held no stations")

    text = [
        "# Generated by tools/gen-material-traders.py. Do not edit by hand — rerun the tool.",
        f"# Source: {SOURCE}",
        f"# Commit: {OMH_COMMIT} (jixxed/ed-odyssey-materials-helper, MIT), built from the game's",
        "# MaterialTrade events. Frozen: a station that got a trader after the source was written",
        "# is not listed.",
        "# Game data is Frontier's, used under their media usage rules; see NOTICE.",
        f"# Rows: {len(rows)}.",
        "\t".join(COLUMNS),
    ]
    for market_id in sorted(rows):
        kind, system, station = rows[market_id]
        text.append("\t".join([str(market_id), kind, system, station]))

    OUTPUT.write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(rows)} rows to {OUTPUT}")


if __name__ == "__main__":
    main()
